"""LLM Gateway integration (HTTP contract only; nothing is imported from the gateway project).

When SEMCACHE_GENERATION_BASE_URL is set, cache misses are generated by calling that OpenAI-compatible endpoint
(POST {base}/chat/completions) with the gateway key. The cache never bypasses the gateway: if the gateway denies, rate-limits or fails
a request, that outcome is returned to the caller; there is no fallback to calling OpenAI directly with the gateway down.
Embeddings are not sent through the gateway (they use SEMCACHE_OPENAI_API_KEY / SEMCACHE_OPENAI_BASE_URL).
Contract: docs/gateway_integration.md."""

import httpx

from app.config import Settings


def is_gateway(settings: Settings) -> bool:
    return bool(settings.generation_base_url)


def request_headers(request_id: str) -> dict[str, str]:
    """Identifiers forwarded on every generation call so a gateway log line can be tied to the cache request that caused it."""
    return {"X-Request-ID": request_id, "X-Correlation-ID": request_id}


def gateway_ready(settings: Settings, timeout: float = 2.0) -> bool:
    """Best-effort reachability probe of the gateway's /health (the gateway contract defines it). False if not in gateway mode."""
    if not settings.generation_base_url:
        return False
    base = settings.generation_base_url.rstrip("/")
    root = base[:-3] if base.endswith("/v1") else base
    try:
        return httpx.get(root + "/health", timeout=timeout).status_code == 200
    except httpx.HTTPError:
        return False
